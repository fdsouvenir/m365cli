#!/usr/bin/env python3
"""Generate service references from the executable's public command tree."""
import argparse
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
SERVICES = {
    "mail": ("Read and send Outlook email, or create drafts, using m365cli.", "Draft creation needs mail-write; read/send alone use mail-read and mail-send. Sending requires user authorization. Use read-only checks to test a connection."),
    "calendar": ("Find, create or change Outlook calendar events with m365cli.", "Use delegated authentication. Preserve the person's timezone and verify attendees, start and end before writing. Use calendar-read for reads or calendar-write for read/write access."),
    "contacts": ("Find and maintain Outlook contacts with m365cli.", "Match the existing contact before creating a duplicate; pass only intended changes. Use contacts-read for reads or contacts-write for read/write access."),
    "tasks": ("Manage Microsoft To Do lists and tasks with m365cli.", "Use delegated authentication. Discover the task list ID before reading or changing its tasks. Use tasks-read for reads or tasks-write for read/write access."),
    "onedrive": ("List, download, upload and organize OneDrive files with m365cli.", "Confirm the remote path and conflict behavior before uploads. Downloads are local file writes; do not overwrite unrelated files. Use onedrive-read for reads or onedrive-write for read/write access."),
    "groups": ("Read business Microsoft 365 Groups and membership with m365cli.", "Groups require a business profile and tenant-administrator consent. Teams administration is outside this skill’s scope."),
    "excel": ("Read or edit business Excel worksheets, ranges, tables and rows with m365cli.", "Use delegated business profiles and .xlsx workbooks in business OneDrive or SharePoint. Personal storage and app-only access are unavailable. Excel cannot be read-only: even workbook reads require Files.ReadWrite, granting read and write access to all of the person’s OneDrive files, not just workbooks. Find the drive item ID with OneDrive first. Read the target range/table before changing it. Use --dry-run previews; then read back the result. Matrix files are rectangular JSON arrays; null leaves a range cell unchanged. Use --field formulas explicitly for formulas. Do not retry an uncertain append: inspect the table first to avoid duplicate rows. Range output is JSON even in text mode so matrices remain intact."),
}

def help_tree(binary, path):
    result = subprocess.run([str(binary), *path, "--help"], check=True, text=True, capture_output=True)
    content = result.stdout
    parts = ["## `m365cli " + " ".join(path) + "`\n\n```text\n" + content.strip() + "\n```\n"]
    if "\nCOMMANDS\n" in content:
        section = content.split("\nCOMMANDS\n", 1)[1].split("\nLEARN MORE", 1)[0]
        children = re.findall(r"^  ([a-z][a-z0-9-]*)\b", section, re.M)
        for child in dict.fromkeys(children):
            parts.extend(help_tree(binary, [*path, child]))
    return parts

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path, default=ROOT / "bin/m365cli")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for service, (description, instructions) in SERVICES.items():
        folder = ROOT / "skills" / ("m365cli-" + service)
        documents = {
            folder / "SKILL.md": f"---\nname: m365cli-{service}\ndescription: {description}\n---\n\n# {service.title()}\n\nUse a specific `--account NAME` on every API command and `--json` for structured output.\nRead the core m365cli skill for setup or permission changes. Never fall back to a different account.\n\n{instructions}\n\nRead [the generated command reference](references/commands.md) for syntax. Confirm with\n`m365cli {service} COMMAND --help` when needed. Only perform writes requested by the person.\n",
            folder / "references/commands.md": "# Generated command reference\n\nGenerated by `scripts/generate-skills.py` from the executable. Do not edit manually.\n\n" + "\n".join(help_tree(args.binary.resolve(), [service])),
        }
        for file, content in documents.items():
            if args.check:
                if not file.exists() or file.read_text() != content:
                    stale.append(str(file.relative_to(ROOT)))
            else:
                file.parent.mkdir(parents=True, exist_ok=True)
                file.write_text(content)
    if stale:
        sys.exit("Stale generated skills: " + ", ".join(stale))
    print("Service skills checked." if args.check else "Generated 7 service skills and command references.")

if __name__ == "__main__":
    main()
